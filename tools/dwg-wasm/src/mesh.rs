//! Готовые сетки чертежа (MESH).
//!
//! Объём в DWG бывает не только телами ACIS. Сетка — второй распространённый
//! способ, и в чертежах, пришедших из Revit, SketchUp или 3ds Max, он основной:
//! в проверочном файле на 60 МБ ровно ноль тел и 10 590 сеток.
//!
//! Работы здесь несравнимо меньше, чем с телами: у сетки уже есть вершины и
//! грани, резать границу из поверхностей не нужно. Остаётся разложить
//! многоугольники на треугольники и посчитать нормали — этим и занят модуль.

use acadrust::entities::Mesh as DwgMesh;

use crate::tess::Mesh;
use crate::xform::V3;

/// Перекладывает сетку чертежа в нашу.
///
/// Вершины берутся как есть, в осях чертежа: место копии добавит матрица
/// вставки, ровно как у тел. Уровень сглаживания (`subdivision_level`) не
/// применяется — показываем базовую сетку, ту же, что видно в AutoCAD при
/// выключенном сглаживании. Досчитывать подразделение значило бы умножить
/// число треугольников вчетверо на каждый уровень ради разницы, которой на
/// плане площадки не видно.
pub fn build(src: &DwgMesh, out: &mut Mesh) {
    let vertex = |i: usize| -> Option<V3> {
        src.vertices.get(i).map(|p| [p.x, p.y, p.z])
    };

    for face in &src.faces {
        let idx = face.indices();
        if idx.len() < 3 {
            // Грань из двух точек — это ребро, площади у неё нет
            out.skipped += 1;
            continue;
        }

        let Some(a) = vertex(idx[0]) else {
            // Ссылка на несуществующую вершину: битый файл, но не повод
            // терять остальное молча
            out.skipped += 1;
            continue;
        };

        // Веером от первой вершины. Грани MESH из AutoCAD — треугольники и
        // четырёхугольники, для них веер даёт ту же самую поверхность.
        for k in 1..idx.len() - 1 {
            match (vertex(idx[k]), vertex(idx[k + 1])) {
                (Some(b), Some(c)) => out.push_tri(a, b, c, false),
                _ => out.skipped += 1,
            }
        }
    }
}
