//! Источник случайности для wasm.
//!
//! Сами мы случайность не используем — её просит `ahash` внутри acadrust, чтобы
//! засеять хеш-таблицы. Под wasm32-unknown-unknown у `getrandom` нет источника
//! по умолчанию, и без него не собирается вся цепочка.
//!
//! Штатный путь (`getrandom_backend="wasm_js"`) тянет wasm-bindgen ради одного
//! вызова `crypto.getRandomValues`, а с ним — генератор JS-обвязки в сборку.
//! Ради одного числа это дорого, поэтому берём семя у хозяина модуля: одна
//! импортируемая функция, никакой обвязки.
//!
//! Почему семя вообще важно, а не просто константа: ключи хеш-таблиц берутся из
//! разбираемого файла, то есть из недоверенных данных. С постоянным семенем
//! файл можно собрать так, чтобы все ключи попали в одну корзину и разбор
//! захлебнулся. Вкладка чужого вреда не причинит, но подвесить её обидно.

/// Семя, которое даёт хозяин модуля при загрузке.
///
/// Хранится в статике, а не запрашивается каждый раз: обращение к хозяину
/// заметно дороже арифметики, а `ahash` дёргает источник часто.
static mut SEED: u64 = 0;

/// Принимает семя от хозяина. Вызывается один раз сразу после создания модуля.
#[no_mangle]
pub extern "C" fn dwg_seed(seed: u64) {
    // wasm однопоточный: гонки здесь невозможны по устройству среды.
    unsafe { SEED = seed | 1 };
}

/// SplitMix64 — простой и быстрый генератор с хорошим распределением.
/// Криптостойкость тут не нужна: задача лишь в том, чтобы состав файла
/// нельзя было заранее подогнать под расположение корзин.
fn next_u64() -> u64 {
    unsafe {
        SEED = SEED.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = SEED;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
}

/// Точка, которую ждёт getrandom при `getrandom_backend="custom"`.
///
/// # Safety
/// Вызывающая сторона отвечает за то, что `dest` указывает на доступные для
/// записи `len` байт — это контракт самого getrandom.
#[no_mangle]
unsafe extern "Rust" fn __getrandom_v03_custom(
    dest: *mut u8,
    len: usize,
) -> Result<(), getrandom::Error> {
    let mut written = 0;
    while written < len {
        let chunk = next_u64().to_le_bytes();
        let take = core::cmp::min(8, len - written);
        core::ptr::copy_nonoverlapping(chunk.as_ptr(), dest.add(written), take);
        written += take;
    }
    Ok(())
}
