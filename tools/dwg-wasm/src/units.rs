//! Единицы чертежа.
//!
//! В сцене один юнит — это метр, а чертежи почти всегда в миллиметрах. Без
//! пересчёта модель приезжает в тысячу раз больше площадки и накрывает собой
//! весь проект.
//!
//! Нужное число лежит в самом файле: переменная заголовка `INSUNITS`. Её
//! коды заданы форматом DWG и не меняются от версии к версии.

/// Метрическая ли единица.
///
/// Нужно, чтобы отличить осмысленно проставленные единицы от оставшихся от
/// шаблона: имперский шаблон подписывает чертёж дюймами независимо от того,
/// в чём его на самом деле чертили.
fn is_metric(insunits: i16) -> bool {
    matches!(insunits, 4..=7 | 11..=17)
}

/// Во сколько метров превращается один юнит чертежа.
///
/// Подписи в заголовке верим только когда она метрическая.
///
/// Звучит произвольно, но за этим измерение: проверочный чертёж подписан
/// дюймами и «имперской» системой, а вычерчен в миллиметрах — по подписи сцена
/// вышла бы в двадцать пять раз крупнее натуры. `INSUNITS` сплошь и рядом
/// достаётся от шаблона и не имеет отношения к содержимому, причём имперский
/// шаблон в этой роли встречается чаще всего.
///
/// Поэтому имперская и пустая подпись считаются не сказанными, и берутся
/// миллиметры — в них ведётся почти вся рабочая документация. Ошибиться здесь
/// не страшно: единицы переключаются в свойствах объекта одним щелчком, а вот
/// молча увеличить модель в двадцать пять раз — страшно.
pub fn resolve(insunits: i16) -> (f64, &'static str) {
    if is_metric(insunits) {
        to_meters(insunits)
    } else {
        (0.001, "миллиметры")
    }
}

/// Множитель и название по коду `INSUNITS`, как он задан форматом DWG.
pub fn to_meters(insunits: i16) -> (f64, &'static str) {
    match insunits {
        1 => (0.0254, "дюймы"),
        2 => (0.3048, "футы"),
        3 => (1609.344, "мили"),
        4 => (0.001, "миллиметры"),
        5 => (0.01, "сантиметры"),
        6 => (1.0, "метры"),
        7 => (1000.0, "километры"),
        8 => (0.0254e-6, "микродюймы"),
        9 => (0.0254e-3, "милы"),
        10 => (0.9144, "ярды"),
        11 => (1e-10, "ангстремы"),
        12 => (1e-9, "нанометры"),
        13 => (1e-6, "микроны"),
        14 => (0.1, "дециметры"),
        15 => (10.0, "декаметры"),
        16 => (100.0, "гектометры"),
        17 => (1e9, "гигаметры"),
        21 => (1200.0 / 3937.0, "футы США"),
        22 => (100.0 / 3937.0, "дюймы США"),
        23 => (3600.0 / 3937.0, "ярды США"),
        // 0 — чертёж без указания единиц, и это самый частый случай в старых
        // файлах. Берём миллиметры: в них ведётся почти вся рабочая
        // документация, а человек всё равно увидит, что мы предположили,
        // и сможет переключить.
        _ => (0.001, "не указаны, считаем миллиметрами"),
    }
}
