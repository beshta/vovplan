/**
 * Пределы размера загружаемых файлов.
 *
 * Собраны в одном месте, потому что предел один на всё приложение — плагин
 * multipart настраивается при регистрации, — а нужды у маршрутов разные, и
 * разница тут не косметическая.
 *
 * Модель пишется на диск потоком: гигабайт пройдёт мимо памяти. А вот значок
 * проекта, превью и аватар сначала целиком читаются в память и оттуда
 * отдаются в sharp. Поднять общий предел до трёхсот мегабайт и оставить всё
 * как есть — значит подарить любому участнику способ занять триста мегабайт
 * оперативной памяти одним запросом к загрузке аватара, а несколькими
 * подряд — уронить бэкенд на тесном VPS.
 *
 * Поэтому общий предел равен самому большому из нужных, а маршруты с чтением
 * в память сужают его для себя.
 */

const MB = 1024 * 1024;

/** Модель: пишется потоком на диск, поэтому предел щедрый */
export const MODEL_LIMIT = 300 * MB;

/** Карта высот: тоже потоком, но столько ей не нужно и близко */
export const TERRAIN_LIMIT = 64 * MB;

/** Картинки интерфейса — аватар, значок, превью: читаются в память целиком */
export const IMAGE_LIMIT = 8 * MB;

/** Общий предел плагина — по самому большому из нужных */
export const MAX_UPLOAD = MODEL_LIMIT;

/** «300 МБ» для сообщений человеку */
export const mb = (bytes: number) => `${Math.round(bytes / MB)} МБ`;
